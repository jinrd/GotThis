CREATE TABLE field_definition (
    id            BIGINT            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_list_id  BIGINT            NOT NULL,
    name          VARCHAR(50)       NOT NULL,
    type          VARCHAR(20)       NOT NULL,
    options       JSONB,
    sort_order    DOUBLE PRECISION  NOT NULL,
    created_at    TIMESTAMP(6)      NOT NULL,
    updated_at    TIMESTAMP(6)      NOT NULL,
    CONSTRAINT fk_field_definition_task_list FOREIGN KEY (task_list_id)
        REFERENCES task_list (id) ON DELETE CASCADE,
    CONSTRAINT uk_field_definition_name UNIQUE (task_list_id, name),
    CONSTRAINT ck_field_definition_type
        CHECK (type IN ('TEXT', 'NUMBER', 'DATE', 'CHECKBOX', 'SELECT')),
    CONSTRAINT ck_field_definition_options
        CHECK ((type = 'SELECT') = (options IS NOT NULL))
);

ALTER TABLE task
    ADD COLUMN properties JSONB NOT NULL DEFAULT '{}'::jsonb;

ALTER TABLE task
    ADD CONSTRAINT ck_task_properties_object CHECK (jsonb_typeof(properties) = 'object');
