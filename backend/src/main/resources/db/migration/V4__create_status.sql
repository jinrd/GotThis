CREATE TABLE status (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_list_id  BIGINT       NOT NULL,
    name          VARCHAR(30)  NOT NULL,
    sort_order    INTEGER      NOT NULL,
    is_done       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_status_task_list FOREIGN KEY (task_list_id)
        REFERENCES task_list (id) ON DELETE CASCADE,
    CONSTRAINT uk_status_list_name UNIQUE (task_list_id, name)
);

CREATE INDEX idx_status_list_sort ON status (task_list_id, sort_order);

-- 기존 목록에도 기본 상태 3개를 넣는다
INSERT INTO status (task_list_id, name, sort_order, is_done, created_at, updated_at)
SELECT t.id, s.name, s.sort_order, s.is_done, now(), now()
FROM task_list t
CROSS JOIN (VALUES ('할 일', 1, FALSE),
                   ('진행 중', 2, FALSE),
                   ('완료', 3, TRUE)) AS s(name, sort_order, is_done);
