CREATE TABLE task (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_list_id  BIGINT        NOT NULL,
    status_id     BIGINT        NOT NULL,
    parent_id     BIGINT,
    title         VARCHAR(200)  NOT NULL,
    description   VARCHAR(2000),
    priority      VARCHAR(10)   NOT NULL DEFAULT 'NONE',
    due_date      DATE,
    sort_order    INTEGER       NOT NULL,
    created_at    TIMESTAMP(6)  NOT NULL,
    updated_at    TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_task_task_list FOREIGN KEY (task_list_id)
        REFERENCES task_list (id) ON DELETE CASCADE,
    CONSTRAINT fk_task_status FOREIGN KEY (status_id)
        REFERENCES status (id),
    CONSTRAINT fk_task_parent FOREIGN KEY (parent_id)
        REFERENCES task (id) ON DELETE CASCADE,
    CONSTRAINT ck_task_priority CHECK (priority IN ('NONE', 'LOW', 'MEDIUM', 'HIGH'))
);

CREATE INDEX idx_task_list         ON task (task_list_id);
CREATE INDEX idx_task_status_sort  ON task (status_id, sort_order);
CREATE INDEX idx_task_parent       ON task (parent_id);
